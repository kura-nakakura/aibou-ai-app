def prompt_block() -> str:
    """CHATのsystem promptへ入れる圧縮版。

    「使い方は？」「何ができるの？」と聞かれたときに、実装に無い機能を
    でっち上げずに答えられるようにするための最小限の事実。
    """
    lines = [
        "【このアプリについて（利用者に説明するときの正しい情報）】",
        f"名前は {APP_NAME}。話しかけると、タスク・予定の登録、調べ物、資料づくりまで実際に手を動かす。",
        "画面（モード）: HOME(今日の状況) / CHAT(会話) / ME(体調記録) / TASKS(タスク) / "
        "BOARD(付箋・自動化) / VAULT(資料から回答) / CODE(コード) / STUDIO(資料・スライド生成) / "
        "CAPTURE(録画録音・文字起こし) / SNS / INCOME / AUTO / ARCHIVE。",
        "設定は右上の歯車。KEYCHAIN に GEMINI_API_KEY か HUGGINGFACE_TOKEN を入れると動く。"
        "CORE で見た目（ダーク/ライト）とコアの形を変えられる。",
        "秘書的な使い方の例:「明日15時に歯医者」「今日は何からやるのがいい？」"
        "「毎朝7時にニュースを要約して通知」「牛乳のタスク完了にして」。",
        "現在はベータ版。データの置き場: 各自が自分の Supabase を繋ぐ方式。設定 → KEYCHAIN → "
        "「自分のデータベース」で URL と service_role キーを入れて接続する。"
        "繋ぐまではどこにも保存されない（再読み込みで消える）ので、最初に繋ぐよう案内すること。"
        "自分のデータは自分のDBに入り、他の人からは見えない。",
        "分からないこと・実装に無い機能は、あるかのように答えないこと。",
    ]
    return "\n".join(lines)


def status(owner: bool = True) -> dict:
    """UIが出し分けるための要約。

    shared_data は「みんなが同じ置き場を使っている」かどうか。ここを固定値に
    しておくと、利用者ごとのDB接続を入れたあとも「共有です」と言い続けて
    しまう（逆もある）。データの置き場の説明を間違えるのは事故なので、
    実際の設定から出す。
    利用者を識別できないと自分のDBには振り分けられない = 共有のまま。
    """
    per_user_db = bool(config.SUPABASE_JWT_SECRET)
    return {
        "app": APP_NAME,
        "section_count": len(sections(owner)),
        "mode_count": len(modes(owner)),
        "beta": True,
        "shared_data": not per_user_db,
    }
